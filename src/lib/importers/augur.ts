import { parseNumeric } from "../format";
import { workbookMatrices } from "./matrix";

export type AugurDeal = {
  opportunityName: string;
  amount: number | null;
  age: number | null;
  closeDate: string | null;
  expectedMonthlyAppraisals: number | null;
  weeklyGoal: number | null;
  actualUploads: number | null;
  diff: number | null;
};

export type AugurWorkbook = {
  asOf: string | null;
  generatedBy: string | null;
  weekOf: string | null;
  deals: AugurDeal[];
  annualVolumePreOctober: number | null;
  weeklyGoalTotal: number | null;
  uploadsTotal: number | null;
};

function findHeader(rows: string[][]): { index: number; cols: Record<string, number> } | null {
  for (let i = 0; i < rows.length; i += 1) {
    const joined = rows[i].join(" ").toLowerCase();
    if (joined.includes("opportunity name") && joined.includes("amount")) {
      const cols: Record<string, number> = {};
      rows[i].forEach((cell, index) => {
        const key = cell.toLowerCase();
        if (key.includes("opportunity")) cols.name = index;
        else if (key === "amount") cols.amount = index;
        else if (key === "age") cols.age = index;
        else if (key.includes("close")) cols.close = index;
        else if (key.includes("expected")) cols.expected = index;
        else if (key.includes("weekly goal")) cols.weeklyGoal = index;
        else if (key === "diff") cols.diff = index;
        else if (/^\d{4}-\d{2}-\d{2}$/.test(cell)) cols.actual = index;
      });
      return { index: i, cols };
    }
  }
  return null;
}

export function parseAugurMatrices(sheets: { name: string; rows: string[][] }[]): AugurWorkbook | null {
  for (const sheet of sheets) {
    const header = findHeader(sheet.rows);
    if (!header) continue;
    let asOf: string | null = null;
    let generatedBy: string | null = null;
    for (const row of sheet.rows.slice(0, header.index)) {
      const text = row.join(" ");
      const match = /As of\s+(.+?)\s+•\s+Generated by\s+(.+)/i.exec(text);
      if (match) {
        asOf = match[1].trim();
        generatedBy = match[2].trim();
      }
    }
    const weekOf = header.cols.actual != null ? sheet.rows[header.index][header.cols.actual] : null;
    const deals: AugurDeal[] = [];
    let annualVolumePreOctober: number | null = null;
    let weeklyGoalTotal: number | null = null;
    let uploadsTotal: number | null = null;
    for (const row of sheet.rows.slice(header.index + 1)) {
      const name = header.cols.name != null ? row[header.cols.name]?.trim() : "";
      const blob = row.join(" ");
      if (/annual volume pre-october/i.test(blob)) {
        annualVolumePreOctober = parseNumeric(row.find((cell, index) => index !== header.cols.name && cell) || "");
        continue;
      }
      if (/^weekly goal$/i.test(name || "")) {
        weeklyGoalTotal = parseNumeric(row[header.cols.amount] || row[header.cols.weeklyGoal] || "");
        continue;
      }
      if (!name) {
        const expected = header.cols.expected != null ? parseNumeric(row[header.cols.expected]) : null;
        const uploads = header.cols.actual != null ? parseNumeric(row[header.cols.actual]) : null;
        if (uploads != null) uploadsTotal = uploads;
        if (expected != null && weeklyGoalTotal == null && header.cols.weeklyGoal != null) {
          weeklyGoalTotal = parseNumeric(row[header.cols.weeklyGoal]);
        }
        continue;
      }
      deals.push({
        opportunityName: name,
        amount: header.cols.amount != null ? parseNumeric(row[header.cols.amount]) : null,
        age: header.cols.age != null ? parseNumeric(row[header.cols.age]) : null,
        closeDate: header.cols.close != null ? row[header.cols.close] || null : null,
        expectedMonthlyAppraisals: header.cols.expected != null ? parseNumeric(row[header.cols.expected]) : null,
        weeklyGoal: header.cols.weeklyGoal != null ? parseNumeric(row[header.cols.weeklyGoal]) : null,
        actualUploads: header.cols.actual != null ? parseNumeric(row[header.cols.actual]) : null,
        diff: header.cols.diff != null ? parseNumeric(row[header.cols.diff]) : null,
      });
    }
    return { asOf, generatedBy, weekOf, deals, annualVolumePreOctober, weeklyGoalTotal, uploadsTotal };
  }
  return null;
}

export async function parseAugurWorkbook(buffer: Buffer): Promise<AugurWorkbook | null> {
  return parseAugurMatrices(await workbookMatrices(buffer));
}
